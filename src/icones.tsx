export type IconName = keyof typeof ICONS;

export function Ico({ name, className }: { name: IconName; className?: string }) {
  const C = ICONS[name];
  return <C className={'ico' + (className ? ' ' + className : '')} strokeWidth={2.25} aria-hidden />;
}
